export default {
  async load(E) {
    g = E.makeG2D(E.W, E.H);
    await Promise.all(Object.keys(SLOTS).map((s) => loadSlot(E, s)));
    buildWords(E);
    // cuts sit on analysed beats: snap every shot boundary to the nearest entry of audio.json "beats"
    const snap = (x) => { const n = E.next("beats", x - 0.03); return n && Math.abs(n.t - x) < 0.06 ? n.t : x; };
    for (const sh of SHOTS) { sh.t0 = snap(sh.t0); sh.t1 = snap(sh.t1); }
    LY = layouts(E);
    EN = entries();
    const c = g.ctx;
    // sticker / headword / definition layouts per entry (cached; base sticker size 200 px design)
    ST = EN.map((en) => K.stickerLayout(E, c, en.rows, 200 * E.SCALE));
    HD = EN.map((en, i) => K.headLayout(E, c, en.head, LY["P" + en.id].hw.size));
    DF = EN.map((en) => { const d = LY["P" + en.id].def; return K.defLayout(E, c, en.def, d.size, d.maxW); });
    // her lines as captions (F, Z, A1, A2)
    const line = (l, heroes = [], size = LY.cap.size) => K.lineLayout(E, c, V[l].map((x, i) => ({ txt: x.w, w: x, hero: heroes.includes(i) })), size);
    LINES = {
      8: line(8, [0, 1]), 9: line(9, [2]), 10: line(10, [3]), 12: line(12, [0]), 13: line(13, [5]), 14: line(14, [2]),
      15: line(15, [4]), 16: line(16, [2]),
      11: K.lineLayout(E, c, V[11].map((x, i) => ({ txt: x.w, w: x, hero: i === 0 })), (E.ORIENT === "portrait" ? 96 : 120) * E.SCALE),
    };
    CARDS = Array.from({ length: 10 }, (_, i) => F.makeCard(E, i, E.SCALE));
  },
  async prepare(E, t) {
    const sh = shotAt(t), cl = CL[sh.slot];
    if (cl) await cl.v.frame(localT(sh, t));
  },
  render(E, t, rt) {
    const S = E.SCALE, c = g.ctx, sh = shotAt(t);
    E.renderer.setRenderTarget(rt);
    E.hud.theme = "light";
    E.hud.sub = false;
    if (sh.id.startsWith("P")) renderPage(E, c, t, sh);
    else if (sh.id === "F") renderFilm(E, c, t, sh);
    else if (sh.id === "Z") renderZero(E, c, t, sh);
    else if (sh.id === "A1") renderCU(E, c, t, sh);
    else renderPlate(E, c, t, sh);
  },
};

// two-pass helper: BACK (ground + type behind) -> plate (matte cut-out) -> FRONT
