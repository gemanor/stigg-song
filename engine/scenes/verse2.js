const CL = {}; // slot -> {v, name}
async function loadSlot(E, slot) {
  for (const name of SLOTS[slot]) {
    try { CL[slot] = { v: await E.loadVideo(name), name }; return; } catch (e) { console.warn("verse2: clip missing", name); }
  }
}
